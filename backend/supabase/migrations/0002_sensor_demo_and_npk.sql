-- FarmIQ — migration 0002: demo-mode sensor records + NPK/pH columns.
--
-- Run in the Supabase SQL editor (or `supabase db push`):
--   supabase/migrations/0002_sensor_demo_and_npk.sql
--
-- Why:
--   * ``is_demo`` marks readings produced by the built-in sensor simulator so
--     they can never be confused with, or overwrite, real hardware readings.
--     Default false, so every existing/real row stays non-demo.
--   * The simulator also emits soil NPK and pH, which the original schema did
--     not store. Adding them here keeps demo and real rows structurally
--     identical (a real ESP32 can POST the same fields).
--
-- This migration is additive and idempotent: it does not touch existing data.

alter table public.sensor_readings
    add column if not exists is_demo      boolean not null default false,
    add column if not exists nitrogen     double precision,
    add column if not exists phosphorous  double precision,
    add column if not exists potassium    double precision,
    add column if not exists ph           double precision;

comment on column public.sensor_readings.is_demo is
    'true = generated by the DEMO sensor simulator; false = real hardware reading';

create index if not exists sensor_readings_owner_demo_idx
    on public.sensor_readings (owner_id, is_demo, created_at desc);
