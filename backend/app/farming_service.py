def _resource_assessment(payload: dict[str, Any], alternatives: list[dict]) -> list[dict[str, Any]]:
    resources = payload.get("resources") or {}
    available_ids = {a["id"]: a for a in alternatives}
    out: list[dict[str, Any]] = []
    for key, label in _RESOURCE_LABELS.items():
        provided = bool(resources.get(key))
        related = [
            available_ids[aid]["name"]
            for aid in _RESOURCE_ALTERNATIVES.get(key, [])
            if aid in available_ids
        ]
        out.append({
            "resource": label,
            "available": provided,
            "usable_for": related,
        })
    other = [str(o).strip() for o in (resources.get("other") or []) if str(o).strip()]
    if other:
        out.append({
            "resource": "Other organic material",
            "available": True,
            "usable_for": other,
        })
    return out


def _warnings(payload: dict[str, Any], content: dict[str, Any]) -> list[str]:
    """Non-blocking, honest warnings tailored to the farmer's situation."""
    warnings: list[str] = []
    preference = payload["preference"]
    resources = payload.get("resources") or {}
    has_onfarm_organic = any(
        bool(resources.get(k)) for k in ("cow_dung", "compost", "crop_residues")
    )

    if preference == "organic" and not has_onfarm_organic:
        warnings.append(
            "You have not reported any on-farm organic material. Without a reliable "
            "supply of manure, compost or crop residues, an organic-only plan risks "
            "nutrient deficiency and yield loss. Start by building a compost supply."
        )
    if preference == "organic" and payload.get("current_pesticide"):
        warnings.append(
            "Do not stop pesticide use abruptly during an active outbreak. Move to "
            "scouting-based IPM first and keep an approved option available."
        )
    if preference in ("organic", "integrated") and payload.get("current_fertilizer"):
        warnings.append(
            "Reduce fertiliser gradually, one input at a time, and only to the extent a "
            "soil test and your organic-material supply support. Organic sources are not "
            "a kilogram-for-kilogram replacement for fertiliser."
        )
    if payload.get("soil_type") in ("Saline / alkaline", "Sandy", "Laterite"):
        warnings.append(
            f"On {payload['soil_type'].lower()} soil, organic matter is especially "
            "valuable but nutrient availability and pH may need attention — confirm with "
            "a soil test before changing inputs."
        )
    warnings.append(content["cautions"][0])
    return warnings


def _preference_note(pref: dict[str, Any], crop: str) -> str:
    return f"For {crop}, you selected {pref['title']}. {pref['short']} {pref['note']}"


def _fit_note(method: dict[str, Any], payload: dict[str, Any]) -> str:
    """A short, honest note on how a method fits this farmer's situation."""
    resources = payload.get("resources") or {}
    has_onfarm_organic = any(
        bool(resources.get(k)) for k in ("cow_dung", "compost", "crop_residues")
    )
    mid = method["id"]
    if mid == "organic":
        if has_onfarm_organic:
            return "You reported on-farm organic material, which is the main practical prerequisite for this method."
        return "You did not report on-farm organic material, which this method depends on. Build a compost supply before relying on it."
    if mid == "integrated":
        if payload.get("current_fertilizer") or payload.get("current_pesticide"):
            return "Starting from your current input use, this is usually the lowest-risk first step."
        return "A practical middle path that builds soil health while keeping a nutrient safety net."
    return "Your current practice — the baseline any transition is measured against."


def build_comparison(payload: dict[str, Any], client: Any) -> dict[str, Any]:
    content = load_content()
    validate_context(payload, content)

    methods, content_source, last_updated = get_methods(client)
    crop = payload["crop"]
    preference_id = payload["preference"]
    pref = next(p for p in content["preferences"] if p["id"] == preference_id)

    alternatives, alt_source = get_alternatives(client, crop)

    compared = [{**m, "fit_note": _fit_note(m, payload)} for m in methods]

    return {
        "crop": crop,
        "location": payload.get("location") or None,
        "soil_type": payload["soil_type"],
        "area_acres": payload["area_acres"],
        "preference": preference_id,
        "preference_title": pref["title"],
        "preference_note": _preference_note(pref, crop),
        "methods": compared,
        "organic_alternatives": alternatives,
        "resource_assessment": _resource_assessment(payload, alternatives),
        "recommendation": {
            "summary": (
                f"A side-by-side comparison for {crop} on {payload['soil_type'].lower()} soil. "
                "Cost, yield, labour and water figures are deliberately not estimated by "
                "FarmIQ — use your own records and local sources for those."
            ),
            "nutrient_note": (
                "Do not replace a fertiliser kilogram-for-kilogram with manure. Nutrient "
                "availability, nutrient content, application timing and soil-test results "
                "must all be considered."
            ),
            "next_step": (
                "Compare the three columns, then generate a gradual transition plan that "
                "matches your resources and preference."
            ),
        },
        "warnings": _warnings(payload, content),
        "cautions": content["cautions"],
        "definition_notes": content["definition_notes"],
        "legend": content["legend"],
        "sources": {
            "note": content["metadata"]["source_note"],
            "integrity_note": content["metadata"]["integrity_note"],
            "content_source": content_source,
            "alternatives_source": alt_source,
            "last_updated": last_updated,
        },
        "disclaimer": content["metadata"]["disclaimer"],
    }


# ─────────────────────────────────────────────────────────────────────────
# Transition plan
# ─────────────────────────────────────────────────────────────────────────

def build_transition_plan(payload: dict[str, Any], client: Any) -> dict[str, Any]:
    content = load_content()
    validate_context(payload, content)

    crop = payload["crop"]
    preference_id = payload["preference"]
    pref = next(p for p in content["preferences"] if p["id"] == preference_id)
    _, content_source, last_updated = get_methods(client)

    phases = []
    for phase in content["transition_framework"]["phases"]:
        steps = [dict(s) for s in phase["steps"]]
        if phase["id"] == "assessment":
            steps.insert(0, {
                "text": (
                    f"Your reported current practice for {crop}: fertiliser "
                    f"'{payload.get('current_fertilizer') or 'not stated'}', pesticide "
                    f"'{payload.get('current_pesticide') or 'not stated'}'."
                ),
                "status": "guidance",
            })
        if phase["id"] == "first_practices" and preference_id == "modern":
            steps.insert(0, {
                "text": (
                    "You chose modern farming. Staying with recommended doses is a valid "
                    "choice; the low-risk additions below still improve soil health without "
                    "threatening yield."
                ),
                "status": "guidance",
            })
        phases.append({**phase, "steps": steps})

    resources = payload.get("resources") or {}
    available = [label for key, label in _RESOURCE_LABELS.items() if resources.get(key)]
    other = [str(o).strip() for o in (resources.get("other") or []) if str(o).strip()]

    return {
        "crop": crop,
        "preference": preference_id,
        "preference_title": pref["title"],
        "area_acres": payload["area_acres"],
        "current_practice": {
            "fertilizer": payload.get("current_fertilizer") or None,
            "pesticide": payload.get("current_pesticide") or None,
            "note": "Recorded from your input. Keep your own yield and cost records to compare against later.",
        },
        "phases": phases,
        "costs_and_resources": {
            "status": "unavailable",
            "estimated_cost_per_acre": None,
            "unit": "INR / acre",
            "note": (
                "FarmIQ does not estimate transition costs or yields. Build the budget from "
                "your own records and current local rates from your KVK / State Agriculture "
                "Department."
            ),
            "reported_on_farm_materials": available,
            "reported_other_materials": other,
        },
        "decision_indicators": content["decision_indicators"],
        "cautions": content["cautions"],
        "uncertainty_note": (
            "Yields may change during a transition — they are not guaranteed to stay the "
            "same, and they are not guaranteed to fall. Outcomes depend on your soil, water, "
            "crop and management. Monitor and adjust."
        ),
        "professional_advice_note": (
            "For a whole-farm change, seek local professional agricultural advice (Krishi "
            "Vigyan Kendra, State Agriculture Department or an extension officer) before you "
            "act."
        ),
        "sources": {
            "content_source": content_source,
            "last_updated": last_updated,
            "note": content["metadata"]["source_note"],
        },
        "disclaimer": content["metadata"]["disclaimer"],
    }
