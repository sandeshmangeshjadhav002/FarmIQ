"""Organic vs. modern farming: reference content + deterministic planning logic.

Design principles (these are deliberate, not incidental):

* **No fabricated numbers.** FarmIQ never produces a cost, yield, labour or
  water *figure* for this feature. Region-, crop- and market-specific numbers
  cannot be generalised honestly, so they are marked ``unavailable`` and the
  farmer is pointed at a local authoritative source. The curated content in
  ``app/data/farming_methods.json`` is the source of truth.
* **PostgreSQL first, file fallback.** The reference content can be seeded into
  Supabase (see ``supabase/migrations/0003_farming_methods.sql`` and
  ``scripts/seed_farming_methods.py``). When the tables are absent or empty the
  bundled curated file is served instead, so the feature works before the
  migration is applied — the same resilience pattern used for weather.
* **Deterministic output.** The comparison and the transition plan are built by
  rules from the curated content and the farmer's own inputs. Nothing here is
  generated by an LLM or by RAG, and nothing is random.
"""
from __future__ import annotations

import json
import logging
from functools import lru_cache
from pathlib import Path
from typing import Any

from .errors import InputValidationError

logger = logging.getLogger("farmiq.farming")

_DATA_FILE = Path(__file__).resolve().parent / "data" / "farming_methods.json"

# Resource key -> the alternatives it can realistically supply.
_RESOURCE_ALTERNATIVES: dict[str, list[str]] = {
    "cow_dung": ["fym", "compost"],
    "compost": ["compost", "vermicompost"],
    "crop_residues": ["residue_mulch", "compost", "green_manure"],
}

_RESOURCE_LABELS = {
    "cow_dung": "Cow dung / farmyard manure",
    "compost": "Compost",
    "crop_residues": "Crop residues",
}


@lru_cache(maxsize=1)
def load_content() -> dict[str, Any]:
    """Load and cache the curated reference content file."""
    with open(_DATA_FILE, "r", encoding="utf-8") as fh:
        content = json.load(fh)
    logger.info(
        "Loaded farming-methods reference content: %d methods, %d alternatives",
        len(content.get("methods", [])),
        len(content.get("alternatives", [])),
    )
    return content


# ─────────────────────────────────────────────────────────────────────────
# Content resolution: PostgreSQL first, curated file as fallback
# ─────────────────────────────────────────────────────────────────────────

def _rows_or_none(client: Any, table: str) -> list[dict] | None:
    """Return rows from a Supabase table, or None if unavailable/empty.

    A missing table (migration not applied) or an unconfigured client must not
    break the feature, so any failure falls back to the curated file.
    """
    if client is None:
        return None
    try:
        resp = client.table(table).select("*").execute()
    except Exception as exc:  # noqa: BLE001 - deliberate: degrade to file fallback
        logger.info("Farming content table '%s' unavailable (%s); using file.", table, exc)
        return None
    data = getattr(resp, "data", None)
    if not data:
        return None
    return data


def get_methods(client: Any) -> tuple[list[dict], str, str]:
    """Return ``(methods, content_source, last_updated)``.

    ``content_source`` is ``"database"`` or ``"reference_file"`` so callers can
    state where the guidance came from.
    """
    content = load_content()
    rows = _rows_or_none(client, "farming_methods")
    if rows:
        methods = []
        for row in sorted(rows, key=lambda r: r.get("sort_order") or 0):
            payload = row.get("payload") or {}
            if payload:
                item = dict(payload)
                if row.get("last_updated"):
                    item["last_updated"] = str(row["last_updated"])[:10]
                methods.append(item)
        if methods:
            return methods, "database", content["metadata"]["last_updated"]
    return content["methods"], "reference_file", content["metadata"]["last_updated"]


def get_alternatives(client: Any, crop: str | None = None) -> tuple[list[dict], str]:
    """Return ``(alternatives_for_crop, content_source)``."""
    content = load_content()
    rows = _rows_or_none(client, "organic_alternatives")
    source = "reference_file"
    alternatives = content["alternatives"]
    if rows:
        loaded = [r.get("payload") or {} for r in rows]
        loaded = [a for a in loaded if a]
        if loaded:
            alternatives = loaded
            source = "database"
    if crop:
        alternatives = [a for a in alternatives if _crop_matches(a.get("crops", []), crop)]
    return alternatives, source


def _crop_matches(crops: list[str], crop: str) -> bool:
    """True when an alternative applies to the selected crop.

    ``"*"`` means "any crop". Matching is case-insensitive and tolerant of the
    "Paddy" vs "Paddy (Rice)" style of naming used in the catalogue.
    """
    if "*" in crops:
        return True
    wanted = crop.strip().lower()
    for entry in crops:
        candidate = str(entry).strip().lower()
        if not candidate or candidate == "*":
            return True
        if candidate == wanted or candidate in wanted or wanted in candidate:
            return True
    return False


# ─────────────────────────────────────────────────────────────────────────
# Validation
# ─────────────────────────────────────────────────────────────────────────

def validate_context(payload: dict[str, Any], content: dict[str, Any]) -> None:
    """Validate the crop/soil/preference context; raise 422 with structure.

    Values are never silently coerced: an unsupported crop or preference is
    rejected with a message that lists what is supported.
    """
    errors: list[dict[str, Any]] = []

    crop = (payload.get("crop") or "").strip()
    if not crop:
        errors.append({"field": "crop", "message": "Select a crop."})
    elif crop not in content["supported_crops"]:
        errors.append({
            "field": "crop",
            "value": crop,
            "message": f"'{crop}' is not in the supported crop list.",
            "supported": content["supported_crops"],
        })

    soil = (payload.get("soil_type") or "").strip()
    if not soil:
        errors.append({"field": "soil_type", "message": "Select a soil type."})
    elif soil not in content["soil_types"]:
        errors.append({
            "field": "soil_type",
            "value": soil,
            "message": f"'{soil}' is not in the supported soil list.",
            "supported": content["soil_types"],
        })

    preference = (payload.get("preference") or "").strip().lower()
    allowed = {p["id"] for p in content["preferences"]}
    if preference not in allowed:
        errors.append({
            "field": "preference",
            "value": payload.get("preference"),
            "message": "Select a farming preference.",
            "supported": sorted(allowed),
        })

    area = payload.get("area_acres")
    if area is None:
        errors.append({"field": "area_acres", "message": "Enter the farm size in acres."})
    else:
        try:
            if float(area) <= 0:
                errors.append({
                    "field": "area_acres",
                    "value": area,
                    "message": "Farm size must be greater than zero.",
                })
        except (TypeError, ValueError):
            errors.append({
                "field": "area_acres",
                "value": area,
                "message": "Farm size must be a number of acres.",
            })

    if errors:
        raise InputValidationError(
            "Input validation failed. Correct the highlighted values and try again.",
            errors=errors,
        )


