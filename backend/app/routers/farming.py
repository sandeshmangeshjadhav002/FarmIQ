"""Organic vs. modern farming advisor endpoints.

The comparison and the transition plan are produced deterministically from the
curated reference content (``app/data/farming_methods.json``, optionally seeded
into Supabase) plus the farmer's own inputs. Nothing is generated by an LLM and
no cost, yield, labour or water figure is invented — see ``farming_service``.

Endpoints
---------
``GET  /api/farming-methods``                    – methods, options, legend, sources.
``GET  /api/farming-methods/organic-alternatives`` – crop-filtered alternatives.
``POST /api/farming-methods/compare``            – deterministic side-by-side comparison.
``POST /api/farming-methods/transition-plan``    – deterministic gradual transition plan.
``GET  /api/farming-methods/plans``              – the caller's saved plans.

The two GET reference endpoints are public (they expose no user data, like
``/api/schemes``). The POST endpoints and the saved-plan list require
authentication, and any ``farm_id`` supplied is verified against the caller's
own farms before use.
"""
from __future__ import annotations

from typing import Any, Optional

from fastapi import APIRouter, Depends, Query

from app import db, farming_service
from app.auth import AuthUser, get_current_user
from app.schemas import (
    FarmingContextRequest,
    FarmingOptionsResponse,
    FarmingPlanListResponse,
)
from app.supabase_client import get_optional_admin_client

router = APIRouter()


def _owned_farm_id(payload: FarmingContextRequest, user: AuthUser, client: Any) -> Optional[str]:
    """Verify the caller owns ``farm_id`` before it is used (defence in depth)."""
    if not payload.farm_id:
        return None
    # Raises 404 when the farm does not exist for this owner — users can only
    # act on their own farm records.
    db.get_farm(client, user.id, payload.farm_id)
    return payload.farm_id


def _maybe_save(kind: str, payload: FarmingContextRequest, result: dict, user: AuthUser, client: Any) -> Optional[dict]:
    """Persist the result when ``save`` is set and return a small reference."""
    if not payload.save:
        return None
    input_data = payload.model_dump()
    row = db.insert_farming_plan(client, user.id, kind, input_data, result)
    return {"id": row.get("id"), "created_at": row.get("created_at"), "kind": kind}


@router.get("/api/farming-methods", response_model=FarmingOptionsResponse)
def get_farming_methods(client: Any = Depends(get_optional_admin_client)):
    """Curated reference content + the options the frontend form needs."""
    content = farming_service.load_content()
    methods, _source, _updated = farming_service.get_methods(client)
    preferences = content["preferences"]
    return {
        "crops": content["supported_crops"],
        "soil_types": content["soil_types"],
        "preferences": preferences,
        "metadata": {**content["metadata"], "methods": methods},
        "legend": content["legend"],
        "definition_notes": content["definition_notes"],
        "cautions": content["cautions"],
    }


@router.get("/api/farming-methods/organic-alternatives")
def get_organic_alternatives(
    crop: Optional[str] = Query(None, min_length=1, max_length=80),
    client: Any = Depends(get_optional_admin_client),
):
    """Organic and integrated alternatives, optionally filtered by crop."""
    alternatives, source = farming_service.get_alternatives(client, crop)
    return {
        "total": len(alternatives),
        "crop": crop,
        "content_source": source,
        "metadata": farming_service.load_content()["metadata"],
        "alternatives": alternatives,
    }


@router.get("/api/farming-methods/plans", response_model=FarmingPlanListResponse)
def list_plans(
    kind: Optional[str] = Query(None, max_length=30),
    limit: int = Query(50, ge=1, le=200),
    offset: int = Query(0, ge=0),
    user: AuthUser = Depends(get_current_user),
    client: Any = Depends(get_optional_admin_client),
):
    """The caller's own saved comparison / transition plans.

    ``client`` cannot be None here because ``get_current_user`` already required
    a working (configured) Supabase client to authenticate the token.
    """
    rows, total = db.list_farming_plans(client, user.id, kind=kind, limit=limit, offset=offset)
    return {"total": total, "plans": rows}


@router.post("/api/farming-methods/compare")
def compare_farming_methods(
    payload: FarmingContextRequest,
    user: AuthUser = Depends(get_current_user),
    client: Any = Depends(get_optional_admin_client),
):
    """Side-by-side comparison for the three farming methods."""
    if payload.farm_id:
        _owned_farm_id(payload, user, client)
    result = farming_service.build_comparison(payload.model_dump(), client)
    saved = _maybe_save("comparison", payload, result, user, client)
    if saved:
        result = {**result, "saved_plan": saved}
    return result


@router.post("/api/farming-methods/transition-plan")
def transition_plan(
    payload: FarmingContextRequest,
    user: AuthUser = Depends(get_current_user),
    client: Any = Depends(get_optional_admin_client),
):
    """A gradual, crop-specific transition plan."""
    if payload.farm_id:
        _owned_farm_id(payload, user, client)
    result = farming_service.build_transition_plan(payload.model_dump(), client)
    saved = _maybe_save("transition_plan", payload, result, user, client)
    if saved:
        result = {**result, "saved_plan": saved}
    return result
