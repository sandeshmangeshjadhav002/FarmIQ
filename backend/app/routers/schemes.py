"""Government agricultural schemes (India) endpoints.

Content lives in a maintainable structured data file
(``app/data/government_schemes.json``) so it can be reviewed and updated
without touching code. Nothing here is generated by an LLM or retrieved by RAG:
it is static, human-verified reference data, and every field that could not be
confirmed from an official source is explicitly marked ``needs_verification``.

Endpoints
---------
``GET /api/schemes``                 – all schemes (+ metadata, legend, cautions).
``GET /api/schemes/{scheme_id}``     – one scheme by id.
``GET /api/schemes?category=...``    – case-insensitive category filter.

Read-only and public: it exposes no user data and no credentials.
"""
from __future__ import annotations

import json
import logging
from functools import lru_cache
from pathlib import Path
from typing import Any

from fastapi import APIRouter, Query

from app.errors import NotFoundError

logger = logging.getLogger("farmiq.schemes")
router = APIRouter()

_DATA_FILE = Path(__file__).resolve().parent.parent / "data" / "government_schemes.json"


@lru_cache(maxsize=1)
def _load() -> dict[str, Any]:
    """Load and cache the structured scheme data file."""
    with open(_DATA_FILE, "r", encoding="utf-8") as fh:
        data = json.load(fh)
    logger.info("Loaded %d government schemes from %s", len(data.get("schemes", [])), _DATA_FILE)
    return data


@router.get("/api/schemes")
def list_schemes(category: str | None = Query(None, min_length=1, max_length=60)):
    """All schemes, optionally filtered by category (case-insensitive)."""
    data = _load()
    schemes = data["schemes"]
    if category:
        wanted = category.strip().lower()
        schemes = [s for s in schemes if s.get("category", "").lower() == wanted]
    return {
        "metadata": data["metadata"],
        "legend": data["legend"],
        "categories": sorted({s.get("category", "") for s in data["schemes"] if s.get("category")}),
        "total": len(schemes),
        "schemes": schemes,
        "additional_support": data["additional_support"],
        "cautions": data["cautions"],
    }


@router.get("/api/schemes/{scheme_id}")
def get_scheme(scheme_id: str):
    """A single scheme by its stable id."""
    for scheme in _load()["schemes"]:
        if scheme["id"] == scheme_id:
            return scheme
    raise NotFoundError(f"Unknown scheme '{scheme_id}'.")
